#!/usr/bin/env python3
"""Build and verify a relocatable native macOS application with PyInstaller."""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import importlib.metadata
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys

PROJECT = Path(__file__).resolve().parents[1]


def make_icon(path: Path) -> None:
    """Encode the official Baidu artwork; source provenance lives beside it."""
    from PIL import Image

    image = Image.open(PROJECT / "hu_lab" / "assets" / "carlife-icon.png").convert("RGBA")
    image.save(path, format="ICO" if path.suffix.lower() == ".ico" else "ICNS")
    image.resize((256, 256), Image.Resampling.LANCZOS).save(path.with_suffix(".png"))


def collect_licenses(destination: Path, library: Path) -> dict[str, str]:
    destination.mkdir(parents=True, exist_ok=True)
    for name in ("LICENSE", "NOTICE", "THIRD_PARTY_NOTICES.md"):
        shutil.copy2(PROJECT / name, destination / name)
    shutil.copy2(PROJECT / "hu_lab" / "assets" / "ICON_SOURCE.json", destination / "Baidu-CarLife-artwork.json")
    versions = {}
    for name in ("PyInstaller", "PySide6", "PySide6_Essentials", "PySide6_Addons", "shiboken6", "av", "Pillow"):
        dist = importlib.metadata.distribution(name)
        versions[name] = dist.version
        target = destination / name
        target.mkdir(exist_ok=True)
        (target / "METADATA.txt").write_text(dist.read_text("METADATA") or f"{name} {dist.version}\n")
        for entry in dist.files or ():
            parts = Path(entry).parts
            # Installer-generated bytecode is not a license and can contain local paths.
            if "__pycache__" in parts or Path(entry).suffix in (".pyc", ".pyo"):
                continue
            if "licenses" in parts or Path(entry).name.upper().startswith(("LICENSE", "COPYING")):
                source = Path(dist.locate_file(entry))
                if source.is_file():
                    # License directory trees can contain multiple license texts.
                    relative = Path(*parts[parts.index("licenses") + 1:]) if "licenses" in parts else Path(entry).name
                    output = target / relative
                    output.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(source, output)
    usb_license = library.resolve().parents[1] / "COPYING"
    if usb_license.is_file():
        shutil.copy2(usb_license, destination / "libusb-COPYING")
    return versions


def verify_native_dependencies(app: Path) -> int:
    """Reject a bundle that still needs Homebrew/workspace native libraries."""
    from macholib.MachO import MachO

    count = 0
    for path in app.rglob("*"):
        if not path.is_file() or path.is_symlink():
            continue
        with path.open("rb") as stream:
            magic = stream.read(4)
        if magic not in (b"\xcf\xfa\xed\xfe", b"\xfe\xed\xfa\xcf", b"\xca\xfe\xba\xbe",
                         b"\xbe\xba\xfe\xca", b"\xfe\xed\xfa\xce", b"\xce\xfa\xed\xfe"):
            continue
        count += 1
        for header in MachO(str(path)).headers:
            for index, name, dependency in header.walkRelocatables():
                if dependency.startswith("/") and not dependency.startswith(("/System/", "/usr/lib/")):
                    raise RuntimeError(f"External native dependency: {path.relative_to(app)} -> {dependency}")
    return count


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dist-dir", type=Path, default=PROJECT / "dist")
    parser.add_argument("--libusb", type=Path, default=Path("/opt/homebrew/opt/libusb/lib/libusb-1.0.dylib"))
    parser.add_argument("--clean", action="store_true", help="Discard PyInstaller analysis cache")
    args = parser.parse_args()
    if sys.platform != "darwin" or platform.machine() != "arm64":
        parser.error("Build with native arm64 Python on an Apple Silicon Mac, outside Rosetta.")
    if not args.libusb.is_file():
        parser.error("libusb not found. Install libusb or pass --libusb /path/to/libusb-1.0.dylib")
    try:
        import PyInstaller
    except ImportError:
        parser.error("PyInstaller missing. Install macos/requirements-build.txt with the same Python.")
    if not (PROJECT / "hu_lab" / "desktop.py").is_file():
        parser.error("Missing hu_lab.desktop entry point")
    build_root = PROJECT / "build" / "mac-headunit"
    assets = build_root / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    make_icon(assets / "HeadUnit.icns")
    # Do not retain files removed from a dependency's license set on later builds.
    if (assets / "licenses").exists():
        shutil.rmtree(assets / "licenses")
    versions = collect_licenses(assets / "licenses", args.libusb)
    (assets / "build-info.json").write_text(json.dumps({
        "name": "CarLife HeadUnit Emulator", "version": "0.3.1", "architecture": "arm64",
        "minimum_macos": "determined from bundled binaries", "python": platform.python_version(),
        "built_utc": datetime.now(timezone.utc).isoformat(), "dependencies": versions,
        "source_sha256": {str(path.relative_to(PROJECT)): hashlib.sha256(path.read_bytes()).hexdigest()
                          for path in sorted([*(PROJECT / "hu_lab").glob("*.py"),
                                             *(PROJECT / "hu_lab" / "assets").glob("*")]) if path.is_file()},
    }, indent=2) + "\n")
    environment = dict(os.environ, CARLIFE_BUILD_ASSETS=str(assets),
                       CARLIFE_BUILD_LIBUSB=str(args.libusb.absolute()),
                       PYINSTALLER_CONFIG_DIR=str(build_root / "cache"))
    # An unrelated source checkout in PYTHONPATH must never enter the app snapshot.
    environment.pop("PYTHONPATH", None)
    command = [sys.executable, "-m", "PyInstaller", "--noconfirm", "--distpath", str(args.dist_dir.absolute()),
               "--workpath", str(build_root / "pyinstaller"), str(PROJECT / "macos" / "CarLifeHeadUnit.spec")]
    if args.clean:
        command.insert(3, "--clean")
    subprocess.run(command, cwd=PROJECT, env=environment, check=True)
    app = args.dist_dir.absolute() / "CarLife HeadUnit Emulator.app"
    executable = app / "Contents" / "MacOS" / "CarLife HeadUnit Emulator"
    subprocess.run(["/usr/bin/codesign", "--verify", "--deep", "--strict", str(app)], check=True)
    architecture = subprocess.check_output(["/usr/bin/lipo", "-archs", str(executable)], text=True).strip()
    if architecture != "arm64":
        raise RuntimeError(f"Expected arm64 executable, got {architecture}")
    check_output = build_root / "bundle-check.json"
    check_output.unlink(missing_ok=True)
    subprocess.run([str(executable), "--bundle-check", "--check-output", str(check_output)],
                   cwd="/private/tmp", env=environment, check=True, timeout=60)
    check = json.loads(check_output.read_text())
    if check["status"] != "PASS" or check["architecture"] != "arm64" or not check["frozen"]:
        raise RuntimeError(f"Bundle validation failed: {check}")
    count = verify_native_dependencies(app)
    print(f"\nReady: {app}\nNative architecture: arm64; {count} standalone native binaries: verified.\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
